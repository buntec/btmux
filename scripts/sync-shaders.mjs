const kebab = (name) =>
  name
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .replace(/([a-z])([A-Z\d])/g, "$1-$2")
    .toLowerCase();
const catalog = [];
for (const name of [...generators, ...effects]) {
  const { componentDefinition: definition } = await import(
    pathToFileURL(require.resolve(`shaders/core/${name}`))
  );
  const params = Object.entries(definition.props).map(([name, prop]) => {
    const ui = prop.ui ?? {};
    const value = prop.default;
    const kind =
      typeof value === "number"
        ? "number"
        : typeof value === "boolean"
          ? "boolean"
          : ui.type === "select"
            ? "select"
            : ui.type === "color"
              ? "color"
              : typeof value === "string"
                ? "text"
                : ui.type === "position"
                  ? "position"
                  : "json";
    return {
      name,
      key: kebab(name),
      label: ui.label ?? name,
      description: prop.description ?? "",
      kind,
      default: value,
      min: ui.min,
      max: ui.max,
      step: ui.step,
      options: ui.options,
      compileTime: prop.compileTime ?? false,
    };
  });
  catalog.push({
    id: kebab(name),
    component: name,
    label: name
      .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
      .replace(/([a-z])([A-Z\d])/g, "$1 $2"),
    description: definition.description,
    category: definition.category,
    kind: definition.requiresChild ? "effect" : "generator",
    usesPointer: definition.usesPointer ?? false,
    params,
  });
}
